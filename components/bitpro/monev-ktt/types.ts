// Generator Daftar Tahun Otomatis (Tahun Berjalan + 1 hingga 2019)
export const getInitialYears = () => {
  const currentYear = new Date().getFullYear();
  const years: string[] = [];
  for (let y = currentYear + 1; y >= 2019; y--) {
    years.push(String(y));
  }
  return years;
};

